import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
execFileSync(process.env.PHP_BINARY||'php',['scripts/verify-update-deletion-failure.php'],{encoding:'utf8',windowsHide:true});
const fixture=JSON.parse(execFileSync(process.env.PHP_BINARY||'php',['scripts/verify-rollback-planner.php'],{encoding:'utf8',windowsHide:true}));
const handoff=require('../electron/services/delta-update-handoff.js');
const result=await handoff.applyPendingDelta(fixture.storage,fixture.version,fixture.root);
assert.equal(result.ok,true,result.error);
assert.equal(fs.readFileSync(fixture.root+'/backend/backend.phar','utf8'),'old phar');
assert.equal(fs.readFileSync(fixture.root+'/frontend/dist/old.js','utf8'),'old asset');
assert.equal(fs.existsSync(fixture.root+'/frontend/dist/new.js'),false);
await handoff.rollback(result.plan);
assert.equal(fs.readFileSync(fixture.root+'/backend/backend.phar','utf8'),'new phar');
fs.writeFileSync(result.plan.staging_dir+'/version.json','corrupt late artifact');
const failed=await handoff.applyPendingDelta(fixture.storage,fixture.version,fixture.root);
assert.equal(failed.ok,false);assert.equal(fs.readFileSync(fixture.root+'/backend/backend.phar','utf8'),'new phar');
assert.equal(JSON.parse(fs.readFileSync(fixture.root+'/version.json')).version,'0.0.10-beta.3');
assert.equal(fs.readFileSync(fixture.root+'/frontend/dist/keep.js','utf8'),'unchanged');
console.log('PASS rollback handoff: verified inverse restores old files, removes new files, rejects corrupt/outside/database snapshots; late failure recovers current PHAR and version');
